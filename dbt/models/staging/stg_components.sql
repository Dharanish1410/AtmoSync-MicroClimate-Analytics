WITH source AS (
    SELECT *
    FROM SNOWFLAKE_LEARNING_DB.PUBLIC.COMPONENTS_STAGING
),
cleaned AS (
    SELECT
        TRIM(COMPONENT_ID) AS COMPONENT_ID,
        TRIM(PRODUCT_ID) AS PRODUCT_ID,
        TRIM(COMPONENT_NAME) AS COMPONENT_NAME,
        COMPONENT_COST_INR,
        RECOVERABLE
    FROM source
    WHERE COMPONENT_ID IS NOT NULL
)
SELECT *
FROM cleaned