WITH source AS (
    SELECT *
    FROM SNOWFLAKE_LEARNING_DB.PUBLIC.PRODUCTS_STAGING
),

cleaned AS (
    SELECT
        TRIM(PRODUCT_ID) AS PRODUCT_ID,
        TRIM(PRODUCT_NAME) AS PRODUCT_NAME,
        TRIM(CATEGORY) AS CATEGORY,

        COALESCE(
            TRY_TO_DECIMAL(NULLIF(TRIM(PRICE), ''), 18, 2),
            TRY_TO_DECIMAL(NULLIF(TRIM(ORIGINAL_PRICE_INR), ''), 18, 2)
        ) AS PRICE,

        TRIM(BRAND) AS BRAND,

        TRY_TO_DECIMAL(
            NULLIF(TRIM(ORIGINAL_PRICE_INR), ''), 18, 2
        ) AS ORIGINAL_PRICE_INR,

        TRY_TO_NUMBER(MANUFACTURING_YEAR) AS MANUFACTURING_YEAR,
        TRY_TO_NUMBER(WARRANTY_MONTHS) AS WARRANTY_MONTHS

    FROM source
    WHERE PRODUCT_ID IS NOT NULL
)

SELECT * FROM cleaned