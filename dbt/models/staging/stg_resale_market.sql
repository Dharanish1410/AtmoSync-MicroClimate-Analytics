WITH source AS (
    SELECT *
    FROM SNOWFLAKE_LEARNING_DB.PUBLIC.RESALE_MARKET_STAGING
),

cleaned AS (
    SELECT
        TRIM(RESALE_ID) AS RESALE_ID,
        TRIM(PRODUCT_ID) AS PRODUCT_ID,

        TRY_TO_DECIMAL(
            NULLIF(TRIM(RESALE_PRICE), ''), 18, 2
        ) AS RESALE_PRICE,

        TRY_TO_DATE(NULLIF(TRIM(RESALE_DATE), '')) AS RESALE_DATE,

        TRIM(CONDITION) AS CONDITION,
        TRIM(MARKETPLACE) AS MARKETPLACE

    FROM source
    WHERE RESALE_ID IS NOT NULL
)

SELECT *
FROM cleaned