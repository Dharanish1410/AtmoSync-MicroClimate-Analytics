WITH source AS (
    SELECT *
    FROM SNOWFLAKE_LEARNING_DB.PUBLIC.WARRANTY_STAGING
),

cleaned AS (
    SELECT
        TRIM(WARRANTY_ID) AS WARRANTY_ID,
        TRIM(PRODUCT_ID) AS PRODUCT_ID,

        TRY_TO_NUMBER(
            NULLIF(TRIM(WARRANTY_MONTHS), '')
        ) AS WARRANTY_MONTHS,

        TRIM(WARRANTY_CLAIM_STATUS) AS WARRANTY_CLAIM_STATUS,
        TRIM(FAILURE_TYPE) AS FAILURE_TYPE,

        TRY_TO_DATE(
            NULLIF(TRIM(FAILURE_DATE), '')
        ) AS FAILURE_DATE,

        TRY_TO_DECIMAL(
            NULLIF(TRIM(REPAIR_COST_INR), ''), 18, 2
        ) AS REPAIR_COST_INR

    FROM source
    WHERE WARRANTY_ID IS NOT NULL
)

SELECT *
FROM cleaned