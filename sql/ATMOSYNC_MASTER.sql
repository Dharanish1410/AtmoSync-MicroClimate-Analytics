-- AtmoSync: ATMOSYNC_MASTER table creation
-- Database: SNOWFLAKE_LEARNING_DB
-- Schema: PUBLIC
-- Grain: one row per product (product-wise aggregations avoid duplicate rows)

CREATE OR REPLACE TABLE SNOWFLAKE_LEARNING_DB.PUBLIC.ATMOSYNC_MASTER AS
SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    P.BRAND,
    P.CATEGORY,
    TRY_TO_DOUBLE(TO_VARCHAR(P.ORIGINAL_PRICE_INR)) AS ORIGINAL_PRICE_INR,
    P.PRICE,
    P.MANUFACTURING_YEAR,
    C.TOTAL_COMPONENTS,
    C.TOTAL_COMPONENT_COST_INR,
    C.AVG_COMPONENT_COST_INR,
    R.TOTAL_RESALE_LISTINGS,
    R.AVG_RESALE_PRICE_INR,
    R.MAX_RESALE_PRICE_INR,
    R.MIN_RESALE_PRICE_INR,
    W.TOTAL_WARRANTY_RECORDS,
    W.PENDING_CLAIMS,
    W.APPROVED_CLAIMS,
    W.REJECTED_CLAIMS,
    W.TOTAL_REPAIR_COST_INR,
    W.AVG_REPAIR_COST_INR
FROM SNOWFLAKE_LEARNING_DB.PUBLIC.PRODUCTS P
LEFT JOIN (
    SELECT
        PRODUCT_ID,
        COUNT(*) AS TOTAL_COMPONENTS,
        SUM(COMPONENT_COST_INR) AS TOTAL_COMPONENT_COST_INR,
        AVG(COMPONENT_COST_INR) AS AVG_COMPONENT_COST_INR
    FROM SNOWFLAKE_LEARNING_DB.PUBLIC.COMPONENTS
    GROUP BY PRODUCT_ID
) C
    ON P.PRODUCT_ID = C.PRODUCT_ID
LEFT JOIN (
    SELECT
        PRODUCT_ID,
        COUNT(*) AS TOTAL_RESALE_LISTINGS,
        AVG(RESALE_PRICE) AS AVG_RESALE_PRICE_INR,
        MAX(RESALE_PRICE) AS MAX_RESALE_PRICE_INR,
        MIN(RESALE_PRICE) AS MIN_RESALE_PRICE_INR
    FROM SNOWFLAKE_LEARNING_DB.PUBLIC.RESALE_MARKET
    GROUP BY PRODUCT_ID
) R
    ON P.PRODUCT_ID = R.PRODUCT_ID
LEFT JOIN (
    SELECT
        PRODUCT_ID,
        COUNT(*) AS TOTAL_WARRANTY_RECORDS,
        SUM(CASE WHEN WARRANTY_CLAIM_STATUS = 'Pending' THEN 1 ELSE 0 END) AS PENDING_CLAIMS,
        SUM(CASE WHEN WARRANTY_CLAIM_STATUS = 'Approved' THEN 1 ELSE 0 END) AS APPROVED_CLAIMS,
        SUM(CASE WHEN WARRANTY_CLAIM_STATUS = 'Rejected' THEN 1 ELSE 0 END) AS REJECTED_CLAIMS,
        SUM(REPAIR_COST_INR) AS TOTAL_REPAIR_COST_INR,
        AVG(REPAIR_COST_INR) AS AVG_REPAIR_COST_INR
    FROM SNOWFLAKE_LEARNING_DB.PUBLIC.WARRANTY
    GROUP BY PRODUCT_ID
) W
    ON P.PRODUCT_ID = W.PRODUCT_ID
;

-- Verify the master table row count and unique product count.
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT PRODUCT_ID) AS UNIQUE_PRODUCTS
FROM SNOWFLAKE_LEARNING_DB.PUBLIC.ATMOSYNC_MASTER
;

