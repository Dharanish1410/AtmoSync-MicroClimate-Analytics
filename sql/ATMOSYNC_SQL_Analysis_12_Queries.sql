-- AtmoSync: Initial SQL Analysis Queries
-- Database: SNOWFLAKE_LEARNING_DB
-- Schema: PUBLIC
-- Purpose: Product, component, resale-market, and warranty analysis.
-- Note: These queries use the verified table and column names from the project.

USE DATABASE SNOWFLAKE_LEARNING_DB;
USE SCHEMA PUBLIC;

-- 1. Category-wise product analysis
SELECT
    CATEGORY,
    COUNT(*) AS TOTAL_PRODUCTS,
    ROUND(AVG(PRICE), 2) AS AVERAGE_PRICE
FROM PRODUCTS
GROUP BY CATEGORY
ORDER BY TOTAL_PRODUCTS DESC;

-- 2. Brand-wise product analysis
SELECT
    BRAND,
    COUNT(*) AS TOTAL_PRODUCTS,
    ROUND(AVG(PRICE), 2) AS AVERAGE_PRICE
FROM PRODUCTS
GROUP BY BRAND
ORDER BY TOTAL_PRODUCTS DESC;

-- 3. Top 10 products by total component cost
SELECT
    PRODUCT_ID,
    COUNT(*) AS TOTAL_COMPONENTS,
    SUM(COMPONENT_COST_INR) AS TOTAL_COMPONENT_COST_INR
FROM COMPONENTS
GROUP BY PRODUCT_ID
ORDER BY TOTAL_COMPONENT_COST_INR DESC
LIMIT 10;

-- 4. Top 10 resale listings by resale price
SELECT
    PRODUCT_ID,
    COUNT(*) AS TOTAL_LISTINGS,
    MAX(RESALE_PRICE) AS RESALE_PRICE_INR
FROM RESALE_MARKET
GROUP BY PRODUCT_ID
ORDER BY RESALE_PRICE_INR DESC
LIMIT 10;

-- 5. Warranty claim status distribution
SELECT
    WARRANTY_CLAIM_STATUS,
    COUNT(*) AS TOTAL_RECORDS
FROM WARRANTY
GROUP BY WARRANTY_CLAIM_STATUS
ORDER BY TOTAL_RECORDS DESC;

-- 6. Repair cost analysis by warranty claim status
SELECT
    WARRANTY_CLAIM_STATUS,
    COUNT(*) AS TOTAL_RECORDS,
    ROUND(AVG(REPAIR_COST_INR), 2) AS AVERAGE_REPAIR_COST_INR,
    SUM(REPAIR_COST_INR) AS TOTAL_REPAIR_COST_INR
FROM WARRANTY
GROUP BY WARRANTY_CLAIM_STATUS
ORDER BY TOTAL_REPAIR_COST_INR DESC;

-- 7. Original price vs resale price by product
-- If a product has multiple resale records, AVG gives its average resale price.
SELECT
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    P.BRAND,
    P.ORIGINAL_PRICE_INR,
    ROUND(AVG(R.RESALE_PRICE), 2) AS AVG_RESALE_PRICE_INR,
    ROUND(P.ORIGINAL_PRICE_INR - AVG(R.RESALE_PRICE), 2) AS PRICE_DIFFERENCE_INR
FROM PRODUCTS P
INNER JOIN RESALE_MARKET R
    ON P.PRODUCT_ID = R.PRODUCT_ID
GROUP BY
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    P.BRAND,
    P.ORIGINAL_PRICE_INR
ORDER BY PRICE_DIFFERENCE_INR DESC
LIMIT 10;

-- 8. Brand-wise resale analysis
SELECT
    P.BRAND,
    COUNT(R.RESALE_ID) AS TOTAL_RESALE_LISTINGS,
    ROUND(AVG(R.RESALE_PRICE), 2) AS AVERAGE_RESALE_PRICE_INR
FROM PRODUCTS P
INNER JOIN RESALE_MARKET R
    ON P.PRODUCT_ID = R.PRODUCT_ID
GROUP BY P.BRAND
ORDER BY AVERAGE_RESALE_PRICE_INR DESC;

-- 9. Overall product price summary
SELECT
    COUNT(*) AS TOTAL_PRODUCTS,
    ROUND(AVG(PRICE), 2) AS AVERAGE_PRODUCT_PRICE_INR,
    MAX(PRICE) AS MAX_PRODUCT_PRICE_INR,
    MIN(PRICE) AS MIN_PRODUCT_PRICE_INR
FROM PRODUCTS;

-- 10. Overall component cost summary
SELECT
    COUNT(*) AS TOTAL_COMPONENT_RECORDS,
    SUM(COMPONENT_COST_INR) AS TOTAL_COMPONENT_COST_INR,
    ROUND(AVG(COMPONENT_COST_INR), 2) AS AVERAGE_COMPONENT_COST_INR,
    MAX(COMPONENT_COST_INR) AS MAX_COMPONENT_COST_INR
FROM COMPONENTS;

-- 11. Overall resale-market summary
SELECT
    COUNT(*) AS TOTAL_RESALE_LISTINGS,
    SUM(RESALE_PRICE) AS TOTAL_RESALE_VALUE_INR,
    ROUND(AVG(RESALE_PRICE), 2) AS AVERAGE_RESALE_PRICE_INR,
    MAX(RESALE_PRICE) AS MAX_RESALE_PRICE_INR,
    MIN(RESALE_PRICE) AS MIN_RESALE_PRICE_INR
FROM RESALE_MARKET;

-- 12. Overall warranty and repair-cost summary
SELECT
    COUNT(*) AS TOTAL_WARRANTY_RECORDS,
    SUM(REPAIR_COST_INR) AS TOTAL_REPAIR_COST_INR,
    ROUND(AVG(REPAIR_COST_INR), 2) AS AVERAGE_REPAIR_COST_INR,
    MAX(REPAIR_COST_INR) AS MAX_REPAIR_COST_INR,
    MIN(REPAIR_COST_INR) AS MIN_REPAIR_COST_INR
FROM WARRANTY;
